#!/usr/bin/env python3
"""Generate the hardwired int8 weight ROM for tt_um_ejborcherding_conv7x7.

The chip is a 7x7 convolution with 1 input channel and 128 output channels
(128 filters of 7x7). This script writes two files that must always come from
the same weights:
  src/weights_rom.v   -> the ROM that gets taped out
  test/weights.npy    -> the same weights, shape (128, 7, 7), used by the tests

Weight layout
-------------
The canonical array has shape (128, 7, 7) indexed as w[f, ky, kx].
ROM address = f * 49 + ky * 7 + kx, i.e. filter-major, then row, then column.
The chip walks the ROM in this order; the host never sees addresses.

These shapes are also accepted and converted automatically:
  (128, 1, 7, 7)  PyTorch nn.Conv2d(1, 128, 7).weight
  (7, 7, 1, 128)  TensorFlow / Keras Conv2D kernel (HWIO)
  (7, 7, 128)     the same without the input-channel axis

Values must be integers in [-128, 127] (float arrays are accepted only if every
value is already an integer).

Usage
-----
  # random weights (default, seed 1)
  python tools/gen_weights.py
  python tools/gen_weights.py --seed 42

  # from a saved numpy array
  python tools/gen_weights.py --npy my_filter.npy

  # from your own Python function (called with no arguments, returns the array)
  python tools/gen_weights.py --func my_filters:make_filter
  python tools/gen_weights.py --func path/to/my_filters.py:make_filter

  # or import it and call write_rom(weights) from your own script
"""

import argparse
import importlib
import importlib.util
import os
import sys

import numpy as np

KH, KW, NF = 7, 7, 128
N_WEIGHTS = NF * KH * KW  # 6272
ADDR_BITS = (N_WEIGHTS - 1).bit_length()  # 13

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEFAULT_ROM = os.path.join(ROOT, "src", "weights_rom.v")
DEFAULT_NPY = os.path.join(ROOT, "test", "weights.npy")


def random_weights(seed=1):
    """Uniform random int8 weights, shape (128, 7, 7)."""
    rng = np.random.default_rng(seed)
    return rng.integers(-128, 128, size=(NF, KH, KW), dtype=np.int64)


def to_canonical(w):
    """Reshape any accepted layout to (128, 7, 7) = (f, ky, kx), or raise ValueError."""
    if w.shape == (NF, KH, KW):
        return w
    if w.shape == (NF, 1, KH, KW):  # PyTorch OIHW
        return w[:, 0]
    if w.shape == (KH, KW, 1, NF):  # TensorFlow HWIO
        w = w[:, :, 0]
    if w.shape == (KH, KW, NF):
        return np.transpose(w, (2, 0, 1))
    raise ValueError(
        f"weights must have shape {(NF, KH, KW)} (f, ky, kx), {(NF, 1, KH, KW)}, "
        f"{(KH, KW, 1, NF)} or {(KH, KW, NF)}; got {w.shape}"
    )


def validate(weights):
    """Return weights as an int8 (128, 7, 7) array, or raise ValueError."""
    w = to_canonical(np.asarray(weights))
    if not np.issubdtype(w.dtype, np.integer):
        if not np.all(np.isfinite(w)) or not np.all(w == np.round(w)):
            raise ValueError("weights must be integers; quantize them to int8 first")
    w = w.astype(np.int64)
    lo, hi = int(w.min()), int(w.max())
    if lo < -128 or hi > 127:
        raise ValueError(f"weights must be in [-128, 127], got range [{lo}, {hi}]")
    return w.astype(np.int8)


def write_rom(weights, rom_path=DEFAULT_ROM, npy_path=DEFAULT_NPY, source=""):
    """Validate weights and write the Verilog ROM plus the matching test reference."""
    w = validate(weights)
    flat = w.reshape(-1)  # C order on (f, ky, kx) -> address f*49 + ky*7 + kx

    lines = [
        "// AUTO-GENERATED by tools/gen_weights.py -- do not edit by hand.",
        f"// Source: {source}" if source else "// Source: (not recorded)",
        "// 128 filters x 7x7 signed int8 weights. Address = f*49 + ky*7 + kx.",
        "`default_nettype none",
        "",
        "module conv_weights (",
        f"    input  wire [{ADDR_BITS - 1}:0] addr,",
        "    output reg  [7:0]  w",
        ");",
        "  always @(*) begin",
        "    case (addr)",
    ]
    for i, v in enumerate(flat):
        lines.append(f"      {ADDR_BITS}'d{i}: w = 8'h{int(v) & 0xFF:02x};")
    lines += [
        "      default: w = 8'h00;",
        "    endcase",
        "  end",
        "endmodule",
        "",
    ]
    os.makedirs(os.path.dirname(rom_path), exist_ok=True)
    with open(rom_path, "w") as f:
        f.write("\n".join(lines))
    os.makedirs(os.path.dirname(npy_path), exist_ok=True)
    np.save(npy_path, w)
    return w


def load_func(spec):
    """Load 'module:function' or 'path/to/file.py:function' and call it."""
    if ":" not in spec:
        raise ValueError("--func must look like module:function or file.py:function")
    target, fname = spec.rsplit(":", 1)
    if target.endswith(".py") or os.sep in target:
        mod_spec = importlib.util.spec_from_file_location("user_filters", target)
        mod = importlib.util.module_from_spec(mod_spec)
        mod_spec.loader.exec_module(mod)
    else:
        sys.path.insert(0, os.getcwd())
        mod = importlib.import_module(target)
    return getattr(mod, fname)()


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    src = ap.add_mutually_exclusive_group()
    src.add_argument("--seed", type=int, default=1, help="seed for random weights (default 1)")
    src.add_argument("--npy", help="load weights from a .npy file")
    src.add_argument("--func", help="call module:function (or file.py:function) to get weights")
    ap.add_argument("--rom", default=DEFAULT_ROM, help="output Verilog path")
    ap.add_argument("--ref", default=DEFAULT_NPY, help="output reference .npy path for the test")
    args = ap.parse_args()

    if args.npy:
        weights, source = np.load(args.npy), f"npy {args.npy}"
    elif args.func:
        weights, source = load_func(args.func), f"func {args.func}"
    else:
        weights, source = random_weights(args.seed), f"random seed {args.seed}"

    try:
        w = write_rom(weights, args.rom, args.ref, source=source)
    except ValueError as e:
        sys.exit(f"error: {e}")
    nz = int(np.count_nonzero(w))
    print(f"wrote {args.rom} and {args.ref} ({source}); "
          f"range [{w.min()}, {w.max()}], {nz}/{w.size} nonzero")


if __name__ == "__main__":
    main()
